import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const {version}=JSON.parse(await fs.readFile('package.json','utf8'));
const app=path.resolve('release/mac-arm64/创作工作台.app');
const stage=path.resolve('.cache/dmg-stage');
const dmg=path.resolve(`release/CreationWorkbench-${version}-macOS-arm64.dmg`);
await fs.access(path.join(app,'Contents/MacOS/创作工作台'));
await fs.rm(stage,{recursive:true,force:true});await fs.mkdir(stage,{recursive:true});
execFileSync('/usr/bin/ditto',[app,path.join(stage,'创作工作台.app')]);
await fs.symlink('/Applications',path.join(stage,'Applications'));
await fs.copyFile('../INSTALL.md',path.join(stage,'安装说明.txt'));
execFileSync('/usr/bin/hdiutil',['create','-volname','创作工作台 '+version,'-srcfolder',stage,'-ov','-format','UDZO',dmg],{stdio:'inherit'});
execFileSync('/usr/bin/hdiutil',['verify',dmg],{stdio:'inherit'});
await fs.rm(stage,{recursive:true,force:true});
const files=(await fs.readdir('release')).filter(x=>x.endsWith('.dmg')||x.endsWith('-MediaSources.tar.gz'));
const sums=files.map(f=>execFileSync('/usr/bin/shasum',['-a','256',f],{cwd:'release',encoding:'utf8'})).join('');
await fs.writeFile('release/SHA256SUMS.txt',sums);
console.log(dmg);
